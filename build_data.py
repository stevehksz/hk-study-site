def py_of(text):
    res = pinyin(text, style=Style.TONE, heteronym=False)
    out = []
    for ch, (p,) in zip(text, res):
        if ch in PUNCT or ch == ' ':
            out.append('')
        elif p == ch:
            out.append('?')
        else:
            out.append(p)
    return out

def jy_of(text):
    raw = get_jyutping(text)
    out = []
    for ch, j in zip(text, raw):
        if ch in PUNCT or ch == ' ':
            out.append('')
        elif ch in JY_CORRECT:
            out.append(JY_CORRECT[ch])
        elif j is not None:
            out.append(j)
        else:
            out.append('?')
    return out

