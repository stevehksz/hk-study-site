def main():
    seen = set()
    dups = []
    recs = []
    for i, (w, zh, theme, grade) in enumerate(WORDS):
        key = w.lower()
        if key in seen:
            dups.append(w)
            continue
        seen.add(key)
        recs.append({'id': f'hk{i:03d}', 'w': w, 'zh': zh,
                     'theme': theme, 'grade': grade})
    if dups:
        print('⚠️ 重複詞（已去重）：', dups)
    out = os.path.join(WS, '_hk_primary_words.json')
    json.dump(recs, open(out, 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    from collections import Counter
    c = Counter(r['grade'] for r in recs)
    print(f'寫出 {out}：{len(recs)} 詞')
    for g in ['一年級','二年級','三年級','四年級','五年級','六年級']:
        print(f'  {g}: {c.get(g,0)}')
    print('  主題數：', len(set(r["theme"] for r in recs)))

if __name__ == '__main__':
    main()
