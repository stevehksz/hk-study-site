PUNCT = ' ，。、？！；：（）《》　' + "'"

def norm(s): return ''.join(c for c in s if c not in PUNCT)

def g(e): return e.get('author',''), ''.join(e.get('paragraphs',[]) or [])

print('加载仓库索引(排除 rank 空版)...', flush=True)
t0=time.time()
idx=[]
for root,dirs,fs in os.walk(CP):
    if '.git' in root.split(os.sep): continue
    for f in fs:
        if f.endswith('.json') and 'rank' not in f:
            try: d=json.load(open(os.path.join(root,f),encoding='utf-8'))
            except: continue
            if isinstance(d,list):
                for e in d:
                    if isinstance(e,dict): idx.append((f,e))
print('条目',len(idx),'用时',round(time.time()-t0,1),'s', flush=True)

# 首字索引（快且准）：key = 正文首字（去标点）
char_index = {}
for fp,e in idx:
    au,par = g(e)
    if par:
        nc = norm(par)
        if nc:
            char_index.setdefault(nc[0], []).append((au,par,fp))
print('首字索引桶',len(char_index), flush=True)

import re
SPLIT_RE = re.compile(r'([，。？！；：、])')

def split_lines(paras):
    out=[]; buf=''
    for seg in SPLIT_RE.split(paras):
        if seg in '，。？！；：、':
            buf+=seg; out.append(buf); buf=''
        else:
            buf+=seg
    if buf: out.append(buf)
    return [x for x in out if x.strip()]

def fetch(display, author, first):
    if display in OVERRIDE: return 'OVERRIDE', OVERRIDE[display]
    fn = norm(first)
    cands = char_index.get(fn[0], []) if fn else []
    cands = [c for c in cands if norm(c[1]).startswith(fn)]
    if not cands: return 'MISS', None
    f=[c for c in cands if c[0] and (c[0] in author or author in c[0])]
    pick = f[0] if f else cands[0]
    return 'OK '+pick[2].split(os.sep)[-1], split_lines(pick[1])

